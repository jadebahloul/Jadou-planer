export function optionLabel(options: Option[] | undefined, value: unknown): string {
  if (value == null || value === '') return '';
  return options?.find((o) => o.value === String(value))?.label ?? String(value);
}

export function optionColor(options: Option[] | undefined, value: unknown): string | undefined {
  return options?.find((o) => o.value === String(value))?.color;
}

export function categoryColor(cat: string | null | undefined): string {
  return CATEGORIES.find((c) => c.value === cat)?.color ?? '#A39391';
}
