/**
 * Jadou Planner — single source of truth for every data entity.
 *
 * The registry drives:
 *  - the Prisma schema (server/scripts/gen-prisma.ts)
 *  - server-side validation & coercion (server/src/validate.ts)
 *  - generic forms, tables and filters in the web app
 *
 * Storage conventions (single-user, local app):
 *  - `date`      → "YYYY-MM-DD" string (local day)
 *  - `datetime`  → "YYYY-MM-DDTHH:mm" string (local time, no timezone shifts)
 *  - `time`      → "HH:mm"
 *  - `json`/`tags` → serialized JSON string in SQLite, parsed by the API
 */

export type FieldType =
  | 'string'
  | 'text'
  | 'number'
  | 'money'
  | 'int'
  | 'boolean'
  | 'date'
  | 'datetime'
  | 'time'
  | 'enum'
  | 'ref'
  | 'json'
  | 'tags'
  | 'url'
  | 'image'
  | 'color'
  | 'rating';

export interface Option {
  value: string;
  label: string;
  color?: string;
}

export interface FieldDef {
  type: FieldType;
  label: string;
  required?: boolean;
  options?: Option[];
  ref?: string;
  /** what happens to this row when the referenced row is deleted */
  onDelete?: 'cascade' | 'nullify';
  default?: unknown;
  min?: number;
  max?: number;
  /** not shown in generic forms (managed by the app) */
  hidden?: boolean;
  placeholder?: string;
  help?: string;
  /** shown as a column in generic tables */
  list?: boolean;
  /** span both columns in forms */
  wide?: boolean;
}

export interface ResourceDef {
  label: string;
  plural: string;
  titleField: string;
  orderBy: { field: string; dir: 'asc' | 'desc' };
  search: string[];
  /** date field used by global search / analytics */
  dateField?: string;
  fields: Record<string, FieldDef>;
  /** private health data etc. — never sent to AI unless enabled */
  sensitive?: boolean;
}

